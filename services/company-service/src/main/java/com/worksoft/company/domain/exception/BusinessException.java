package com.worksoft.company.domain.exception;

public final class BusinessException extends RuntimeException {
  public enum Code {
    VALIDATION_ERROR,
    FORBIDDEN,
    COMPANY_NOT_FOUND,
    COMPANY_CONFLICT,
    IDEMPOTENCY_CONFLICT,
    TEMPORARILY_UNAVAILABLE,
    ACCOUNT_NOT_FOUND,
    ACCOUNT_CONFLICT,
    ACCOUNT_VERSION_CONFLICT,
    ACCOUNT_HIERARCHY_CONFLICT,
    PARTY_NOT_FOUND,
    PARTY_CONFLICT,
    VERSION_CONFLICT,
    VOUCHER_NOT_FOUND,
    VOUCHER_POSTED,
    VOUCHER_UNBALANCED,
    INVALID_JOURNAL_LINE,
    POSTING_REFERENCE_INVALID,
    FACTURACION_NO_ENCONTRADA,
    PRODUCTO_DUPLICADO,
    CONFIGURACION_FACTURACION_INVALIDA,
    REFERENCIA_FACTURACION_INVALIDA,
    DOCUMENTO_NO_EDITABLE,
    REVERSO_FACTURACION_INVALIDO,
    PAGO_FACTURACION_INVALIDO,
    NOMINA_NO_ENCONTRADA,
    NOMINA_REFERENCIA_INVALIDA,
    NOMINA_CASO_NO_SOPORTADO,
    NOMINA_PARAMETROS_INVALIDOS,
    NOMINA_DEDUCCIONES_INVALIDAS,
    NOMINA_PERIODO_CERRADO,
    NOMINA_RECALCULAR,
    NOMINA_REGISTRO_DUPLICADO,
    NOMINA_SUPERPOSICION
  }

  private final Code code;

  public BusinessException(Code code) {
    super(code.name());
    this.code = code;
  }

  public Code code() {
    return code;
  }
}
